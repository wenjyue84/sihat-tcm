"""Runtime check: the standalone /patient/report/{id} page renders a saved
report in an isolated iframe with a working Print button. Logs in as the demo
patient via the quick-login button (no AI/quota needed). Exit 0 = all pass."""
import sys
from playwright.sync_api import sync_playwright

BASE = "https://tcm.wenjyue.com"
RID = "e84db4a6-9691-4ac1-9eac-e8dd702c7cca"  # a real demo-patient session id

with sync_playwright() as p:
    b = p.chromium.launch(headless=True)
    pg = b.new_page()
    pg.goto(BASE + "/login")
    pg.wait_for_load_state("networkidle")
    pg.click("button[data-role='patient']")
    pg.wait_for_url("**/patient", timeout=20000)

    pg.goto(BASE + "/patient/report/" + RID)
    pg.wait_for_load_state("networkidle")
    pg.wait_for_timeout(1000)

    has_print = pg.locator("#rp-print").count() > 0
    has_back = pg.locator("a[href='/patient']").count() > 0
    body_text = ""
    try:
        body_text = pg.frame_locator("#report-host iframe").locator("body").inner_text(timeout=6000)
    except Exception as e:
        body_text = "ERR:" + str(e)
    b.close()

checks = [
    ("print button present", has_print),
    ("back link present", has_back),
    ("iframe renders report header", "Sihat TCM" in body_text),
    ("iframe renders report footer", "Generated by Sihat TCM" in body_text),
]
passed = sum(1 for _, ok in checks if ok)
for name, ok in checks:
    print(("PASS" if ok else "FAIL"), name)
print("RESULT %d/%d" % (passed, len(checks)))
print("IFRAME:", body_text[:120].replace("\n", " "))
sys.exit(0 if passed == len(checks) else 1)
